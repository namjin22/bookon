CREATE TABLE TBL_BOOK (
    BOOK_ID    NUMBER(6)           NOT NULL,
    TITLE      VARCHAR2(300 CHAR)  NOT NULL,
    AUTHOR     VARCHAR2(100 CHAR)  NOT NULL,
    PUBLISHER  VARCHAR2(100 CHAR),
    TOTAL_QTY  NUMBER(3)           DEFAULT 1 NOT NULL,
    AVAIL_QTY  NUMBER(3)           NOT NULL,
    USE_YN     CHAR(1)             DEFAULT 'Y' NOT NULL,
    REG_DATE   DATE                DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_BOOK        PRIMARY KEY (BOOK_ID),
    CONSTRAINT CK_BOOK_TOTAL  CHECK (TOTAL_QTY >= 1),
    CONSTRAINT CK_BOOK_AVAIL  CHECK (AVAIL_QTY BETWEEN 0 AND TOTAL_QTY),
    CONSTRAINT CK_BOOK_USE_YN CHECK (USE_YN IN ('Y', 'N'))
);

CREATE TABLE TBL_STUDENT (
    STUDENT_ID    NUMBER(6)          NOT NULL,
    STUDENT_NO    VARCHAR2(10 CHAR)  NOT NULL,
    STUDENT_NAME  VARCHAR2(30 CHAR)  NOT NULL,
    PHONE         VARCHAR2(13 CHAR),
    USE_YN        CHAR(1)            DEFAULT 'Y' NOT NULL,
    REG_DATE      DATE               DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_STUDENT        PRIMARY KEY (STUDENT_ID),
    CONSTRAINT UQ_STUDENT_NO     UNIQUE (STUDENT_NO),
    CONSTRAINT CK_STUDENT_USE_YN CHECK (USE_YN IN ('Y', 'N'))
);

CREATE TABLE TBL_LOAN (
    LOAN_ID      NUMBER(8)  NOT NULL,
    STUDENT_ID   NUMBER(6)  NOT NULL,
    BOOK_ID      NUMBER(6)  NOT NULL,
    LOAN_DATE    DATE       DEFAULT TRUNC(SYSDATE) NOT NULL,
    DUE_DATE     DATE       NOT NULL,
    RETURN_YN    CHAR(1)    DEFAULT 'N' NOT NULL,
    RETURN_DATE  DATE,
    CONSTRAINT PK_LOAN           PRIMARY KEY (LOAN_ID),
    CONSTRAINT FK_LOAN_STUDENT   FOREIGN KEY (STUDENT_ID) REFERENCES TBL_STUDENT (STUDENT_ID),
    CONSTRAINT FK_LOAN_BOOK      FOREIGN KEY (BOOK_ID)    REFERENCES TBL_BOOK (BOOK_ID),
    CONSTRAINT CK_LOAN_DUE       CHECK (DUE_DATE >= LOAN_DATE),
    CONSTRAINT CK_LOAN_RETURN_YN CHECK (RETURN_YN IN ('Y', 'N')),
    CONSTRAINT CK_LOAN_RETURN    CHECK ((RETURN_YN = 'N' AND RETURN_DATE IS NULL)
                                     OR (RETURN_YN = 'Y' AND RETURN_DATE IS NOT NULL)),
    CONSTRAINT CK_LOAN_RETURN_DATE CHECK (RETURN_DATE IS NULL OR RETURN_DATE >= LOAN_DATE)
);

CREATE INDEX IX_LOAN_STUDENT ON TBL_LOAN (STUDENT_ID);
CREATE INDEX IX_LOAN_BOOK    ON TBL_LOAN (BOOK_ID);
CREATE INDEX IX_LOAN_RETURN  ON TBL_LOAN (RETURN_YN);

